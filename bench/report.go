package main

import (
	"fmt"
	"strings"
)

var mark = map[string]string{"yes": "✅", "no": "❌", "partial": "◐", "n/a": "–"}

// markdown renders docs/benchmarks/README.md from a report.
func markdown(rep Report) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	w("# Benchmarks\n\n")
	w("Generated by `cd bench && go run .` on %s. Go %s, %s, %s. Median of %d runs per case.\n\n", rep.Date, strings.TrimPrefix(rep.GoVersion, "go"), rep.OS, rep.CPU, rep.Samples)
	w("Do not trust these numbers blindly: run the harness on your own hardware. The corpus is synthetic and deterministic so anyone can reproduce it; see [Method](#method).\n\n")

	w("## Libraries\n\n| Library | Module | Version |\n| --- | --- | --- |\n")
	for _, l := range rep.Libs {
		w("| %s | `%s` | %s |\n", l.Name, l.Module, l.Version)
	}

	w("\n## Fetch: time per link preview\n\n![Fetch time](fetch-time.svg)\n\n")
	w("## Fetch: bytes read per preview\n\n![Bytes read](bytes-read.svg)\n\n")
	w("## Parse: memory per page\n\n![Parse memory](parse-memory.svg)\n\n")
	w("## Parse: time per page\n\n![Parse time](parse-time.svg)\n\n")

	w("## Features\n\nRows marked *measured* were checked by running each library against the fixtures. The others come from reading each library's source at the version above.\n\n")
	w("| Feature |")
	for _, n := range featureLibs {
		w(" %s |", strings.TrimSuffix(n, " (rich)"))
	}
	w("\n| --- |")
	for range featureLibs {
		w(" :-: |")
	}
	w("\n")
	for _, r := range rep.Features {
		label := r.Feature
		if r.Measured {
			label += " *(measured)*"
		}
		w("| %s |", label)
		for _, n := range featureLibs {
			w(" %s |", mark[r.Values[n]])
		}
		w("\n")
	}
	w("\n✅ yes · ◐ partial (for example a relative URL, or any icon instead of the best one) · ❌ no · – not applicable (parse-only library)\n")

	w("\n## Raw numbers\n\n")
	for _, mode := range []string{"fetch", "parse"} {
		w("### %s\n\n| Library | Page | Time/op | Alloc/op | Allocs/op |", mode)
		if mode == "fetch" {
			w(" Body read/op |")
		}
		w("\n| --- | --- | ---: | ---: | ---: |")
		if mode == "fetch" {
			w(" ---: |")
		}
		w("\n")
		for _, m := range rep.Results {
			if m.Mode != mode {
				continue
			}
			if m.Error != "" {
				w("| %s | %s | error: %s | | |\n", m.Lib, m.Page, m.Error)
				continue
			}
			w("| %s | %s | %s | %s | %d |", m.Lib, m.Page, fmtDuration(m.NsPerOp), fmtBytes(float64(m.BytesOp)), m.AllocsOp)
			if mode == "fetch" {
				w(" %s |", fmtBytes(float64(m.ReadPerOp)))
			}
			w("\n")
		}
		w("\n")
	}

	w(`## Method

- **Corpus.** Four generated pages, from a 40 KB blog post to a 1.9 MB product page, shaped like real pages: a full set of Open Graph and Twitter tags, several icons, inline CSS and JavaScript in the head, and a long body with JSON state at the end. The two large pages put their JSON-LD in the body. See ` + "`bench/corpus.go`" + `.
- **Fetch.** Each library downloads the page from a local ` + "`httptest`" + ` server. Parse-only libraries get the response body from ` + "`http.Client.Get`" + `, the way you would wire them into a service. A counting transport records how many body bytes each library actually reads. No real network is involved, so the time is mostly CPU, and the bytes-read chart is the one that predicts real-world latency and bandwidth.
- **Parse.** Each library parses the same in-memory bytes. goscraper has no parse-only API, so it appears only in the fetch charts.
- **metagrab modes.** ` + "`metagrab`" + ` uses ` + "`PreviewFields`" + ` (title, description, Open Graph, Twitter, image, favicon, canonical), which is the closest match to what the other libraries return. ` + "`metagrab (rich)`" + ` adds JSON-LD, which means scanning the body for ` + "`<script type=\"application/ld+json\">`" + `.
- **Fairness.** Each library runs with its defaults. The libraries do not extract the same fields (see the feature table), so less work can be faster. The goquery baseline uses CSS selectors for the same fields metagrab returns.
- **Reproduce.** ` + "`cd bench && go run .`" + ` rewrites this file, the SVG charts and ` + "`results.json`" + `. ` + "`go run . -quick`" + ` takes one sample per case.
`)
	return b.String()
}
